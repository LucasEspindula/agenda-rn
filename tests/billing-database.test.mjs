import {PGlite} from '@electric-sql/pglite';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {test} from 'node:test';
test('billing transaction, permissions, invoice grouping, historical ownership and audit',async()=>{
const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
create table users(id bigint primary key,role text);
create table app_state(id integer primary key,payload jsonb,updated_at timestamptz default now());
create table agenda_access(user_id bigint,professional_id text);
create table billing_entities(id uuid primary key default gen_random_uuid(),name text not null check(length(trim(name)) between 2 and 160),tax_id text,active boolean not null default true,created_at timestamptz default now());
create table billing_records(id uuid primary key default gen_random_uuid(),appointment_id text unique not null,billing_entity_id uuid not null references billing_entities(id),billing_method text not null check(billing_method in ('PARTICULAR','CONVENIO')),payment_status text not null check(payment_status in ('PENDENTE','PAGO')),invoice_number text,received_amount numeric(12,2) check(received_amount>=0),paid_at date,notes text,updated_at timestamptz not null default now(),updated_by bigint references users(id));
create table invoices(id uuid primary key default gen_random_uuid(),billing_entity_id uuid not null references billing_entities(id),invoice_number text not null,issue_date date,total_amount numeric(12,2),paid_at date,created_at timestamptz default now(),unique(billing_entity_id,invoice_number));
create table invoice_billing_records(invoice_id uuid references invoices(id),billing_record_id uuid references billing_records(id),created_at timestamptz default now(),primary key(invoice_id,billing_record_id));
grant all on all tables in schema public to service_role;
insert into users values(1,'general_manager'),(2,'secretary'),(3,'doctor');insert into agenda_access values(2,'d1');`);
await db.exec(readFileSync('supabase/billing-complete.sql','utf8'));
await db.query('insert into app_state(id,payload) values(1,$1)',[{professionals:[{id:'d1',name:'Médico Um'},{id:'d2',name:'Médico Dois'}],patients:[{id:'p1',insurance:'UNIMED'}],appointments:[{id:'a1',doctorId:'d1',patientId:'p1',status:'realized',date:'2026-09-01'},{id:'a2',doctorId:'d1',patientId:'p1',status:'realized',date:'2026-09-02'},{id:'a3',doctorId:'d2',patientId:'p1',status:'realized',date:'2026-09-03'}],cancelledAppointments:[]}]);
await db.exec(readFileSync('supabase/central-doctors.sql','utf8'));
await db.exec(readFileSync('supabase/billing-refinements.sql','utf8'));
await db.exec('set role service_role');
const save=async(kind,data,actor=1)=>(await db.query('select save_billing($1,$2,$3) as id',[actor,kind,data])).rows[0].id;
const get=async(table,id)=>(await db.query('select * from '+table+' where id=$1',[id])).rows[0];
await assert.rejects(()=>save('entity',{name:'Test'},3));
const entity=await save('entity',{name:'Empresa A',person_type:'PJ',tax_id:'12345678000100',active:true});
await assert.rejects(()=>save('entity',{name:'Empresa B',person_type:'PJ',tax_id:'12345678000100'},2));
const link=await save('link',{doctor_id:'d1',billing_entity_id:entity,active:true});
const base={billing_entity_id:entity,billing_method:'CONVENIO',payment_status:'PENDENTE'};
await assert.rejects(()=>save('record',{...base,appointment_id:'a3'},2));
const r1=await save('record',{...base,appointment_id:'a1',received_amount:999},2);
const r2=await save('record',{...base,appointment_id:'a2'},2);
await assert.rejects(()=>save('record',{...base,id:r1,appointment_id:'a3'},2));
assert.equal((await get('billing_records',r1)).received_amount,null);
await assert.rejects(()=>save('record',{...base,appointment_id:'a1'},2));
const invoice=await save('invoice',{billing_entity_id:entity,invoice_number:'100',payer:'UNIMED',issue_date:'2026-09-10',paid_at:'2026-09-15',total_amount:1200,net_amount:1100,record_ids:[r1,r2]});
assert.equal((await get('billing_records',r1)).payment_status,'PAGO');
assert.equal((await get('billing_records',r2)).paid_at,null);
await assert.rejects(async()=>save('record',{...(await get('billing_records',r1)),appointment_id:'a1'},2));
await assert.rejects(()=>save('invoice',{billing_entity_id:entity,invoice_number:'101',payer:'UNIMED',issue_date:'2026-09-10',record_ids:[r1]}));
await save('invoice',{...(await get('invoices',invoice)),record_ids:[r1],paid_at:''});
assert.equal((await get('billing_records',r2)).payment_status,'PENDENTE');
await save('link',{...(await get('billing_doctor_entities',link)),active:false});
assert.equal((await get('billing_records',r1)).billing_entity_id,entity);
assert.ok((await db.query('select count(*)::int as n from billing_audit')).rows[0].n>=7);

await assert.rejects(async()=>save('delete_entity',await get('billing_entities',entity)));
await assert.rejects(async()=>save('delete_link',await get('billing_doctor_entities',link),2));
await save('delete_link',await get('billing_doctor_entities',link));
assert.equal((await get('billing_records',r1)).billing_entity_id,entity);
const unused=await save('entity',{name:'Sem histórico',person_type:'PF',tax_id:'12345678901'});
await save('delete_entity',await get('billing_entities',unused));
assert.equal(await get('billing_entities',unused),undefined);
// A doctor is independent from an agenda; clients cannot overwrite the directory.
const directory=async(kind,data,actor=1)=>(await db.query('select save_doctor_directory($1,$2,$3) as id',[actor,kind,data])).rows[0].id;
await assert.rejects(()=>directory('doctor',{name:'Forbidden',category:'doctor'},2));
const doctor=await directory('doctor',{name:'Médico Central',crm:'123/RS',category:'doctor',active:true});
assert.equal((await db.query('select count(*)::int n from doctor_agendas where doctor_id=$1',[doctor])).rows[0].n,0);
await db.exec("update app_state set payload=jsonb_set(payload,'{professionals}','[]')");
assert.equal((await db.query('select payload from app_state')).rows[0].payload.professionals.length,3);
await directory('agenda',{id:doctor,workStart:'08:00',workEnd:'18:00',active:true});
assert.equal((await db.query('select payload from app_state')).rows[0].payload.professionals.find(d=>d.id===doctor).agendaEnabled,true);
await assert.rejects(()=>directory('doctor',{name:'Duplicado',crm:'123/RS',category:'doctor'}));
// Ineligible attendance is rejected even if the request bypasses client filtering.
await save('link',{doctor_id:'d1',billing_entity_id:entity,active:true});
await db.exec("update app_state set payload=jsonb_set(payload,'{appointments,1,status}',to_jsonb('scheduled'::text))");
await assert.rejects(()=>save('invoice',{billing_entity_id:entity,invoice_number:'200',payer:'UNIMED',issue_date:'2026-09-10',record_ids:[r2]}));
assert.equal((await db.query("select count(*)::int n from invoices where invoice_number='200'")).rows[0].n,0);
const emptyInvoice=await save('invoice',{billing_entity_id:entity,invoice_number:'201',payer:'UNIMED',issue_date:'2026-09-10',record_ids:[]});
assert.ok(emptyInvoice);
await db.exec('reset role;set role anon');
await assert.rejects(()=>save('entity',{name:'Forbidden'}));
await assert.rejects(()=>db.query('select * from billing_audit'));
await db.close();
});
