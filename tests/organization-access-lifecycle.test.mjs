async function save(db,actor,data,secret=null){
 return db.query('select public.save_user_access($1,$2::jsonb,$3::jsonb) as id',[actor,JSON.stringify(data),secret?JSON.stringify(secret):null]);
}
async function membership(db,id){
 const result=await db.query(`select m.role,m.active,u.active as user_active
  from public.organization_memberships m join public.users u on u.id=m.user_id
  join public.organizations o on o.id=m.organization_id
  where m.user_id=$1 and o.slug='rn-gestao'`,[id]);
 return result.rows[0];
}

test('creating a user and changing role keeps the RN Gestão membership in the same transaction',async()=>{
 const db=await fixture();
 try{
  const id=Number((await save(db,1,account('new@example.com'),credentials)).rows[0].id);
  assert.deepEqual(await membership(db,id),{role:'secretary',active:true,user_active:true});
  const count=await db.query('select count(*)::int as count from public.organization_memberships where user_id=$1',[id]);
  assert.equal(count.rows[0].count,1);
  await db.query("insert into public.sessions(user_id,token_hash) values($1,'revoked')",[id]);
  const modified=await db.query('select updated_at from public.users where id=$1',[id]);
  await save(db,1,account('new@example.com','general_manager',{id,updated_at:modified.rows[0].updated_at}));
  assert.deepEqual(await membership(db,id),{role:'general_manager',active:true,user_active:true});
  assert.equal((await db.query('select count(*)::int as count from public.sessions where user_id=$1',[id])).rows[0].count,0);
  assert.equal((await db.query('select count(*)::int as count from public.directory_audit where record_id=$1',[String(id)])).rows[0].count,2);
 }finally{await db.close()}
});

