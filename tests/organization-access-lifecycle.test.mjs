test('deactivation preserves identity, grants, audit and removes sessions; reactivation is explicit',async()=>{
 const db=await fixture();
 try{
  const id=Number((await save(db,1,account('inactive@example.com'),credentials)).rows[0].id);
  await db.query("insert into public.sessions(user_id,token_hash) values($1,'test-session')",[id]);
  assert.equal((await db.query('select public.deactivate_user_access(1,$1) as changed',[id])).rows[0].changed,true);
  assert.deepEqual(await membership(db,id),{role:'secretary',active:false,user_active:false});
  assert.equal((await db.query('select count(*)::int as count from public.sessions where user_id=$1',[id])).rows[0].count,0);
  assert.equal((await db.query('select public.deactivate_user_access(1,$1) as changed',[id])).rows[0].changed,false);
  const audit=await db.query('select count(*)::int as count from public.directory_audit where record_id=$1',[String(id)]);
  assert.equal(audit.rows[0].count,2);
  await save(db,1,account('inactive@example.com','secretary',{id,active:true}));
  assert.deepEqual(await membership(db,id),{role:'secretary',active:true,user_active:true});
  await db.query("insert into public.sessions(user_id,token_hash) values($1,'session-two')",[id]);
  await save(db,1,account('inactive@example.com','secretary',{id}));
  assert.equal((await membership(db,id)).active,true);
  assert.equal((await db.query('select count(*)::int as count from public.sessions where user_id=$1',[id])).rows[0].count,0);
 }finally{await db.close()}
});

test('failed audit rolls back both user and membership; unauthorized and cross-org actions fail closed',async()=>{
 const db=await fixture();
 try{
  await db.exec(`create function public.reject_audit() returns trigger language plpgsql as $$
   begin if new.after_data->>'email'='rollback@example.com' then raise exception 'audit rejected'; end if; return new; end; $$;
   create trigger audit_guard before insert on public.directory_audit for each row execute function public.reject_audit();`);
  await assert.rejects(save(db,1,account('rollback@example.com'),credentials),/audit rejected/);
  assert.equal((await db.query("select count(*)::int as count from public.users where email='rollback@example.com'")).rows[0].count,0);
  assert.equal((await db.query('select count(*)::int as count from public.organization_memberships')).rows[0].count,3);
  await assert.rejects(save(db,2,account('unauthorized@example.com'),credentials),/Acesso restrito/);
  await assert.rejects(db.query('select public.deactivate_user_access(1,1)'),/próprio acesso/);
  await assert.rejects(save(db,1,account('invalid@example.com','secretary',{active:false}),credentials),/deve começar ativo/);
  await db.exec("update public.organization_memberships set active=false where user_id=1");
  await assert.rejects(save(db,1,account('blocked@example.com'),credentials),/Acesso restrito/);
  await db.exec("update public.organization_memberships set active=true where user_id=1");
  await db.exec("insert into public.organizations(slug,name,kind) values('other','Another','CLINIC')");
  await assert.rejects(save(db,1,account('blocked@example.com'),credentials),/Organização de operação inválida/);
 }finally{await db.close()}
});

