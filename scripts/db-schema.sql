-- Gera o DDL do esquema public a partir do catálogo do PostgreSQL (só estrutura, sem dados).
-- Usado por scripts/db-schema.mjs. Somente leitura.
with
rels as (
  select c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.relacl
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p','v','m','S')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
fns as (
  select p.oid, p.proname, p.prokind, p.proacl, pg_get_function_identity_arguments(p.oid) as args
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
acl_grants as (
  -- obj: texto do objeto no GRANT; acl: aclitem[]
  select obj, a.grantee, string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs
  from (
    select format('table public.%I', relname) as obj, relacl as acl from rels where relkind in ('r','p','v','m')
    union all select format('sequence public.%I', relname), relacl from rels where relkind = 'S'
    union all select format('function public.%I(%s)', proname, args), proacl from fns where prokind = 'f'
    union all select format('procedure public.%I(%s)', proname, args), proacl from fns where prokind = 'p'
  ) o, aclexplode(o.acl) a
  where o.acl is not null
  group by obj, a.grantee
),
parts as (
  select 1 as ord, 'header' as k, 0 as sub, concat_ws(E'\n',
    'set check_function_bodies = false;',
    'set client_min_messages = warning;',
    'create schema if not exists public;') as ddl
  union all
  select 2, 'ext', 0, coalesce(string_agg(format('create extension if not exists %I with schema %I;', e.extname, n.nspname), E'\n' order by e.extname), '')
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'
  union all
  select 3, 'types', 0, coalesce(string_agg(format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid)), E'\n' order by t.typname), '')
  from pg_type t join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
  union all
  select 4, 'seq', 0, coalesce(string_agg(format('create sequence if not exists public.%I as %s increment %s minvalue %s maxvalue %s start %s%s;',
    r.relname, format_type(s.seqtypid, null), s.seqincrement, s.seqmin, s.seqmax, s.seqstart, case when s.seqcycle then ' cycle' else '' end), E'\n' order by r.relname), '')
  from rels r join pg_sequence s on s.seqrelid = r.oid
  where r.relkind = 'S' and not exists (select 1 from pg_depend d where d.objid = r.oid and d.deptype = 'i')
  union all
  select 6, 'fn', row_number() over (order by f.proname, f.args)::int, pg_get_functiondef(f.oid) || ';'
  from fns f
  union all
  select 5, 'table', row_number() over (order by r.relname)::int,
    format(E'create table public.%I (\n%s\n)%s;', r.relname,
      (select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
          case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
               else '' end,
          case when a.attnotnull then ' not null' else '' end,
          case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end),
        E',\n' order by a.attnum)
       from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
       where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped),
      case when r.relkind = 'p' then ' partition by ' || pg_get_partkeydef(r.oid) else '' end)
  from rels r where r.relkind in ('r','p')
  union all
  select 7, 'default', 0, coalesce(string_agg(format('alter table only public.%I alter column %I set default %s;',
    r.relname, a.attname, pg_get_expr(ad.adbin, ad.adrelid)), E'
' order by r.relname, a.attnum), '')
  from rels r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
  join pg_attrdef ad on ad.adrelid = r.oid and ad.adnum = a.attnum
  where r.relkind in ('r','p') and a.attgenerated = ''
  union all
  select 7, 'seq-owned', 1, coalesce(string_agg(format('alter sequence public.%I owned by public.%I.%I;', s.relname, t.relname, a.attname), E'\n' order by s.relname), '')
  from rels s join pg_depend d on d.objid = s.oid and d.deptype = 'a' and d.classid = 'pg_class'::regclass
  join pg_class t on t.oid = d.refobjid join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where s.relkind = 'S'
  union all
  select 8, 'view', row_number() over (order by r.relname)::int,
    format(E'create %s public.%I as\n%s', case r.relkind when 'm' then 'materialized view' else 'view' end, r.relname, pg_get_viewdef(r.oid, true))
  from rels r where r.relkind in ('v','m')
  union all
  select 9, 'constraint', row_number() over (order by case co.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'x' then 4 else 5 end, r.relname, co.conname)::int,
    format('alter table only public.%I add constraint %I %s;', r.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join rels r on r.oid = co.conrelid
  where co.contype in ('p','u','c','x') and co.conislocal
  union all
  -- chaves estrangeiras depois dos índices: algumas apontam para índices únicos que não são constraints
  select 10, 'fk', 100000 + row_number() over (order by r.relname, co.conname)::int,
    format('alter table only public.%I add constraint %I %s;', r.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join rels r on r.oid = co.conrelid
  where co.contype = 'f' and co.conislocal
  union all
  select 10, 'index', row_number() over (order by i.indexname)::int, i.indexdef || ';'
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint co join pg_class ic on ic.oid = co.conindid
                    where ic.relname = i.indexname and co.connamespace = 'public'::regnamespace
                      and co.contype in ('p','u','x'))
  union all
  select 11, 'trigger', row_number() over (order by c.relname, t.tgname)::int, pg_get_triggerdef(t.oid, true) || ';'
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and not t.tgisinternal
  union all
  select 12, 'rls', 0, coalesce(string_agg(format('alter table public.%I enable row level security;', relname)
    || case when relforcerowsecurity then format(E'\nalter table public.%I force row level security;', relname) else '' end, E'\n' order by relname), '')
  from rels where relkind in ('r','p') and relrowsecurity
  union all
  select 13, 'policy', row_number() over (order by p.tablename, p.policyname)::int,
    format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename, lower(p.permissive), lower(p.cmd),
      array_to_string(p.roles, ', '),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p where p.schemaname = 'public'
  union all
  select 14, 'comment', 0, coalesce(string_agg(x.c, E'\n' order by x.c), '') from (
    select format('comment on table public.%I is %L;', r.relname, d.description) c
      from rels r join pg_description d on d.objoid = r.oid and d.objsubid = 0 and d.classoid = 'pg_class'::regclass
    union all
    select format('comment on column public.%I.%I is %L;', r.relname, a.attname, d.description)
      from rels r join pg_description d on d.objoid = r.oid and d.objsubid > 0 and d.classoid = 'pg_class'::regclass
      join pg_attribute a on a.attrelid = r.oid and a.attnum = d.objsubid
    union all
    select format('comment on function public.%I(%s) is %L;', f.proname, f.args, d.description)
      from fns f join pg_description d on d.objoid = f.oid and d.classoid = 'pg_proc'::regclass
  ) x
  union all
  select 15, 'revoke', 0, coalesce(string_agg(format('revoke all on %s from public, anon, authenticated;', obj), E'\n' order by obj), '')
  from (select distinct obj from acl_grants) g
  union all
  select 16, 'grant', 0, coalesce(string_agg(format('grant %s on %s to %s;', privs,
    obj, case when grantee = 0 then 'public' else quote_ident(pg_get_userbyid(grantee)) end), E'\n' order by obj, grantee), '')
  from acl_grants where grantee = 0 or pg_get_userbyid(grantee) not in ('postgres','supabase_admin')
),
counts as (
  select concat_ws(' | ',
    'tabelas ' || (select count(*) from rels where relkind in ('r','p')),
    'funções ' || (select count(*) from fns),
    'gatilhos ' || (select count(*) from pg_trigger t join pg_class c on c.oid = t.tgrelid where c.relnamespace = 'public'::regnamespace and not t.tgisinternal),
    'restrições ' || (select count(*) from pg_constraint where connamespace = 'public'::regnamespace and conislocal),
    'índices ' || (select count(*) from pg_indexes where schemaname = 'public'),
    'políticas RLS ' || (select count(*) from pg_policies where schemaname = 'public'),
    'migrações ' || (select count(*) from supabase_migrations.schema_migrations),
    'última ' || (select max(version) from supabase_migrations.schema_migrations)) as c
)
select (select c from counts) as counts,
       string_agg(ddl, E'\n\n' order by ord, sub) filter (where ddl <> '') as ddl
from parts;
