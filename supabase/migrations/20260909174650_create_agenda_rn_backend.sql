create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text not null default '',
  role text not null check (role in ('general_manager','secretary','doctor')),
  password_hash text,
  password_salt text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.agenda_access (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  professional_id text not null,
  unique(user_id, professional_id)
);
create table if not exists public.app_state (
  id integer primary key,
  payload jsonb not null,
  updated_at timestamptz not null default now()
);
create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  token_hash text not null unique,
  user_id bigint not null references public.users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create table if not exists public.agenda_requests (
  id uuid primary key,
  professional_id text not null,
  appointment_id text,
  action text not null check (action in ('create','update','delete')),
  proposed_payload jsonb,
  previous_payload jsonb,
  status text not null default 'pending' check (status in ('pending','accepted','denied')),
  requested_by bigint not null references public.users(id) on delete cascade,
  decided_by bigint references public.users(id) on delete set null,
  decision_note text,
  created_at timestamptz not null default now(),
  decided_at timestamptz
);
create table if not exists public.notifications (
  id uuid primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  type text not null,
  message text not null,
  request_id uuid references public.agenda_requests(id) on delete set null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists public.audit_logs (
  id uuid primary key,
  actor_user_id bigint references public.users(id) on delete set null,
  actor_name text not null,
  actor_role text not null,
  action text not null,
  professional_id text,
  appointment_id text,
  patient_id text,
  description text not null,
  metadata jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_sessions_expiry on public.sessions(expires_at);
create index if not exists idx_agenda_requests_professional_status on public.agenda_requests(professional_id,status);
create index if not exists idx_notifications_user_created on public.notifications(user_id,created_at desc);
create index if not exists idx_audit_logs_created on public.audit_logs(created_at desc);
alter table public.users enable row level security;
alter table public.agenda_access enable row level security;
alter table public.app_state enable row level security;
alter table public.sessions enable row level security;
alter table public.agenda_requests enable row level security;
alter table public.notifications enable row level security;
alter table public.audit_logs enable row level security;
revoke all on table public.users, public.agenda_access, public.app_state, public.sessions, public.agenda_requests, public.notifications, public.audit_logs from anon, authenticated;